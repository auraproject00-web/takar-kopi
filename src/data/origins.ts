/** Lowercase, no accents, single spaces: "Đắk  Lắk" → "dak lak". */
export function normalize(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/gi, 'd')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

const SEARCH_TEXT = new Map(
  ORIGINS.map((o) => [
    o.id,
    normalize(
      [
        o.name,
        ...o.aliases,
        o.country.id,
        o.country.en,
        ISLANDS.find((i) => i.id === o.island)?.searchWords ?? '',
        o.region,
        ...o.varieties,
      ].join(' '),
    ),
  ]),
)

/**
 * Origins containing every word of the query, best first: the exact name,
 * then whole words in the name, then whole words anywhere, then parts of
 * words (only while nothing matches whole, so typing "bal" still finds
 * Bali). Empty query → nothing.
 */
export function searchOrigins(query: string): Origin[] {
  const words = normalize(query).split(' ').filter(Boolean)
  if (words.length === 0) return []
  const hasWord = (text: string, w: string) => ` ${text} `.includes(` ${w} `)
  const scored: { o: Origin; score: number }[] = []
  for (const o of ORIGINS) {
    const text = SEARCH_TEXT.get(o.id)!
    if (!words.every((w) => text.includes(w))) continue
    const name = normalize(o.name)
    const score =
      name === words.join(' ')
        ? 0
        : words.every((w) => hasWord(name, w))
          ? 1
          : words.every((w) => hasWord(text, w))
            ? 2
            : 3
    scored.push({ o, score })
  }
  // Whole words ("bali") beat parts of longer words ("baliem", "bajawa"), and
  // once anything matches whole, the partial hits are dropped as noise.
  const best = Math.min(...scored.map((s) => s.score))
  return scored
    .filter((s) => best === 3 || s.score < 3)
    .sort((a, b) => a.score - b.score)
    .map((s) => s.o)
}

export function findOrigin(id: string | undefined): Origin | undefined {
  return ORIGINS.find((o) => o.id === id)
}
